@pytest.fixture
def struct_model() -> StructuralAnalytical:
    def periodic_signal(amplitude, mi_1, mi_2, mi_3, mi_4, mi_5, t):
        u = 2.0 * torch.pi * t / PERIOD
        return amplitude * (
            1.0
            + mi_1 * torch.cos(u)
            + mi_2 * torch.sin(u)
            + mi_3 * torch.cos(2.0 * u)
            + mi_4 * torch.sin(2.0 * u)
            + mi_5 * torch.cos(3.0 * u)
        )

    return StructuralAnalytical(periodic_signal, ["signal"])


