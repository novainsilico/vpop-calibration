# Mirrors examples/benchmarking/benchmark_fixed_effects.ipynb.
PERIOD = 24.0
MI_NAMES = [f"mi_{j}" for j in range(1, 6)]
TRUE_MI = dict(zip(MI_NAMES, [0.25, 0.18, 0.15, 0.12, 0.08], strict=True))


def compare_estimate(estimated: float, reference: float, reference_name: str) -> dict:
    return {
        reference_name: reference,
        "estimated": estimated,
        "relative_error_pct": 100.0 * (estimated / reference - 1.0),
    }


