@pytest.mark.golden_test("stored_results/test_fixed_effects.yml")
def test_fixed_effects_golden(
    benchmark_data,
    obs_data,
    struct_model,
    synthetic_config,
    model_params,
    monkeypatch,
    golden,
    request,
):
    # Run the full benchmark schedule rather than the shortened pytest schedule.
    monkeypatch.setattr(saem_optimizer, "smoke_test", False)

    nlme_model = NlmeModel(
        structural_model=struct_model,
        df=obs_data,
        input_params=model_params,
        config=synthetic_config,
    )
    nlme_model.optimizer.run()

    model = nlme_model.statistical_model
    mi_values = (
        model.mi_transform(model.log_mi[None, None, :]).detach().cpu().numpy()[0, 0]
    )
    estimated_mi = dict(zip(MI_NAMES, mi_values.tolist(), strict=True))
    log_amplitude_mean = model.population_betas[0].item()
    log_amplitude_variance = model.omega_pop[0, 0].item()
    residual_variance = model.residual_var.additive_variance[0].item()

    amplitudes_by_patient = benchmark_data.groupby("id")["true_amplitude"]
    realized_log_amplitudes = np.log(amplitudes_by_patient.first().to_numpy())
    realized_noise = (
        benchmark_data["value"] - benchmark_data["true_signal"]
    ).to_numpy()

    actual = {
        "parameter_estimates": {
            "log_amplitude_mean": log_amplitude_mean,
            "log_amplitude_variance": log_amplitude_variance,
            "model_intrinsic": estimated_mi,
            "residual_variance": residual_variance,
        },
        "parameter_comparison": {
            "model_intrinsic": {
                name: compare_estimate(estimated_mi[name], true_value, "true")
                for name, true_value in TRUE_MI.items()
            },
            "amplitude_mean": compare_estimate(
                log_amplitude_mean, float(realized_log_amplitudes.mean()), "realized"
            ),
            "amplitude_variance": compare_estimate(
                log_amplitude_variance,
                float(realized_log_amplitudes.var(ddof=1)),
                "realized",
            ),
            "residual_variance": compare_estimate(
                residual_variance, float(realized_noise.var(ddof=1)), "realized"
            ),
        },
        "state": nlme_model.get_state_dict(),
    }
    expected = golden.out["output"]

    if request.config.getoption("--update-goldens"):
        assert actual == expected
    else:
        diff = DeepDiff(
            actual,
            expected,
            ignore_type_in_groups=[(tuple, list), (float, np.float64)],
            math_epsilon=1e-16,
            ignore_nan_inequality=True,
        )
        assert diff == {}
